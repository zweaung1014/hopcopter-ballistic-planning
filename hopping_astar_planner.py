"""A* path planning for a hopping robot on a 2.5D grid map.

Instead of stepping to one of 8 adjacent cells, the robot hops to points on
a circle of radius `hop_radius` around its current position. Neighbors are
generated by sampling `n_angles` evenly spaced directions on that circle and
snapping each candidate landing point to the underlying grid.

Hop feasibility and cost use a ballistic (parabolic) trajectory model based
on Campana & Laumond (2016), "Ballistic motion planning":

    Eq. 4:  xdot(alpha) = sqrt( g * X^2 / (2 * (X * tan(alpha) - Z)) )
    Eq. 2:  z(u) = z_s + u * tan(alpha) - g * u^2 / (2 * xdot^2)

Combined with a leg-energy limit `v_s = xdot / cos(alpha) <= V_max`.
"""

import heapq
import math
import numpy as np

from map2d5 import Map2D5


# --------------------------------------------------------------------------- #
# Ballistic-trajectory primitives (pure functions, unit-testable in isolation)
# --------------------------------------------------------------------------- #

# Small angular slack to keep alpha strictly inside the open feasible interval
# and away from the singularities `X*tan(alpha) = Z` (xdot -> inf) and
# `cos(alpha) = 0` (v_s -> inf).
_ALPHA_EPS = 1e-6


def feasible_alpha_interval(
    X: float,
    Z: float,
    V_max: float,
    g: float,
) -> tuple[float, float] | None:
    """Feasible takeoff-angle interval [alpha_min, alpha_max] for a hop.

    Combines two constraints:

    (i)  Campana Eq. 4 validity: `X*tan(alpha) - Z > 0`, i.e.
         `alpha in (atan2(Z, X), pi/2)`. This branch of atan2 naturally
         handles Z < 0 (downhill): atan2 returns a negative angle, so the
         geometric lower bound simply moves below 0 and the feasibility
         interval widens.

    (ii) Leg energy: `v_s(alpha) = xdot(alpha)/cos(alpha) <= V_max`. From
         Campana Eq. 4 this rearranges to
              X * sin(2 alpha) - Z * cos(2 alpha)  >=  g X^2 / V_max^2 + Z
         Writing the LHS as `R * sin(2 alpha + psi)` with
              R   = sqrt(X^2 + Z^2)
              psi = atan2(-Z, X)
         and letting `K = (g X^2 / V_max^2 + Z) / R`:
           * K >  1  -> no alpha satisfies (ii): leg too weak. Return None.
           * K < -1  -> every alpha satisfies (ii); the velocity interval is
                        the whole real line.
           * else    -> `sin(2 alpha + psi) >= K` gives
                        2 alpha + psi in [asin K, pi - asin K], i.e.
                        alpha_lo_v = (asin K - psi) / 2
                        alpha_hi_v = (pi - asin K - psi) / 2

    The final interval is the intersection of (i) and (ii), shrunk by
    `_ALPHA_EPS` at each end for numerical safety. Returns `None` if empty.
    """
    if X < 1e-9:
        # Degenerate horizontal displacement: not a real hop. The planner's
        # neighbour generator already dedups the current cell, so this is
        # defensive.
        return None

    # (i) Geometric interval from Campana Eq. 4 validity.
    alpha_lo_geom = math.atan2(Z, X)
    alpha_hi_geom = 0.5 * math.pi

    # (ii) Velocity interval from v_s <= V_max.
    R = math.hypot(X, Z)
    psi = math.atan2(-Z, X)
    K = (g * X * X / (V_max * V_max) + Z) / R

    if K > 1.0:
        return None  # even the min v_s exceeds V_max -> leg too weak
    if K < -1.0:
        alpha_lo_vel = -math.inf
        alpha_hi_vel = math.inf
    else:
        asin_K = math.asin(K)
        alpha_lo_vel = 0.5 * (asin_K - psi)
        alpha_hi_vel = 0.5 * (math.pi - asin_K - psi)

    alpha_min = max(alpha_lo_geom, alpha_lo_vel) + _ALPHA_EPS
    alpha_max = min(alpha_hi_geom, alpha_hi_vel) - _ALPHA_EPS

    if alpha_min >= alpha_max:
        return None
    return alpha_min, alpha_max


def _xdot(X: float, Z: float, alpha_s: float, g: float) -> float:
    """Horizontal takeoff velocity (Campana Eq. 4). Caller must ensure the
    denominator is strictly positive, i.e. `alpha_s > atan2(Z, X)`."""
    denom = 2.0 * (X * math.tan(alpha_s) - Z)
    return math.sqrt(g * X * X / denom)


def predict_trajectory(
    c_s: tuple[float, float, float],
    c_g: tuple[float, float, float],
    alpha_s: float,
    g: float,
    n_samples: int = 32,
) -> list[tuple[float, float, float]]:
    """Sample the parabolic arc from `c_s` to `c_g` with takeoff angle `alpha_s`.

    Returns a list of `(x, y, z)` points. The XY projection is the straight
    segment from `c_s[:2]` to `c_g[:2]`; z(u) follows Campana Eq. 2.
    """
    x_s, y_s, z_s = c_s
    x_g, y_g, _ = c_g

    dx = x_g - x_s
    dy = y_g - y_s
    X = math.hypot(dx, dy)
    if X < 1e-9 or n_samples < 2:
        return [c_s, c_g]

    theta = math.atan2(dy, dx)
    cos_t = math.cos(theta)
    sin_t = math.sin(theta)

    xdot = _xdot(X, c_g[2] - z_s, alpha_s, g)  # Campana Eq. 4
    tan_a = math.tan(alpha_s)
    two_xdot_sq = 2.0 * xdot * xdot

    pts: list[tuple[float, float, float]] = []
    for i in range(n_samples):
        u = X * i / (n_samples - 1)
        # Campana Eq. 2 (rewritten in horizontal traversal u in [0, X]):
        z_u = z_s + u * tan_a - g * u * u / two_xdot_sq
        pts.append((x_s + u * cos_t, y_s + u * sin_t, z_u))
    return pts


def min_clearance(
    c_s: tuple[float, float, float],
    c_g: tuple[float, float, float],
    alpha_s: float,
    height_map: Map2D5,
    g: float,
    robot_radius: float,
    epsilon: float,
    max_step: float,
    obstacle_fill: float,
) -> float:
    """Minimum arc-to-terrain clearance over the hop, minus robot radius.

    Marches along the XY segment from `c_s[:2]` to `c_g[:2]` in steps of
    `min(max_step, height_map.resolution / 3)` so the terrain is sampled at
    least ~3x per grid cell (never coarser than the map). At each sample:

      * `u` is the horizontal distance traversed;
      * `z_arc(u)` comes from Campana Eq. 2;
      * `z_terrain` is obtained by bilinear interpolation of the height map,
        with OBSTACLE cells replaced by `obstacle_fill` (a tall-wall value)
        so obstacles show up as blockers rather than as bilinear artefacts.

    Endpoints are trimmed by `epsilon` (in horizontal units) because the arc
    meets the ground at takeoff and landing by definition. Returns the
    minimum of `(z_arc - z_terrain - robot_radius)` over the sampled
    interior. Returns `-inf` if any sample leaves the map (treated as
    infeasible). Returns `+inf` if the interior sample set is empty.
    """
    x_s, y_s, z_s = c_s
    x_g, y_g, z_g = c_g

    dx = x_g - x_s
    dy = y_g - y_s
    X = math.hypot(dx, dy)
    if X < 1e-9:
        return math.inf

    theta = math.atan2(dy, dx)
    cos_t = math.cos(theta)
    sin_t = math.sin(theta)

    Z = z_g - z_s
    xdot = _xdot(X, Z, alpha_s, g)  # Campana Eq. 4
    tan_a = math.tan(alpha_s)
    two_xdot_sq = 2.0 * xdot * xdot

    step = min(max_step, height_map.resolution / 3.0)

    # Interior range in u: (epsilon, X - epsilon). If the hop is too short
    # for any interior sample, we consider it un-obstructed by definition.
    u_lo = epsilon
    u_hi = X - epsilon
    if u_hi <= u_lo:
        return math.inf

    n_interior = max(1, int(math.ceil((u_hi - u_lo) / step)) + 1)

    min_c = math.inf
    for i in range(n_interior):
        if n_interior == 1:
            u = 0.5 * (u_lo + u_hi)
        else:
            u = u_lo + (u_hi - u_lo) * i / (n_interior - 1)

        sx = x_s + u * cos_t
        sy = y_s + u * sin_t

        if not height_map.is_within_bounds(sx, sy):
            return -math.inf  # arc leaves the map -> infeasible

        # Campana Eq. 2 (rewritten in u):
        z_arc = z_s + u * tan_a - g * u * u / two_xdot_sq

        # Skip endpoint-adjacent samples where the robot body has not yet
        # cleared the takeoff column, or has already re-entered the landing
        # column. Along the arc `z_arc(u)` starts at `z_s` (u=0) and ends at
        # `z_g` (u=X). The body-of-the-robot only clears the endpoint ground
        # plane when the arc has risen at least `robot_radius` above it. We
        # do this per-sample rather than solving a quadratic for u because
        # the exact "clear-body" horizontal distance depends on the sign of
        # Z and the arc's asymmetry.
        if (z_arc - z_s) < robot_radius or (z_arc - z_g) < robot_radius:
            continue

        z_terrain = height_map.get_elevation_bilinear(
            sx, sy, obstacle_fill=obstacle_fill
        )
        clearance = z_arc - z_terrain - robot_radius
        if clearance < min_c:
            min_c = clearance

    return min_c


class HoppingAStarPlanner:
    """A* planner for a hopping robot on a 2.5D grid map.

    Every expansion generates candidate landing cells by sampling `n_angles`
    evenly spaced points on a circle of radius `hop_radius` around the
    current cell. A hop is accepted only when a ballistic (parabolic) arc
    exists that:

      * lands within the leg's takeoff-speed budget `V_max`
        (Campana Eq. 4 + `v_s = xdot / cos(alpha) <= V_max`);
      * clears the terrain along the segment with a bilinearly-sampled
        height-map lookup (accounting for robot radius).

    Feasible hops get a base cost (xy distance + asymmetric elevation
    penalty) plus a smooth proximity penalty that grows as the minimum
    arc-to-terrain clearance shrinks toward `clearance_margin`. The A*
    heuristic remains Euclidean XY distance to the goal (admissible: the
    proximity penalty is >= 0 and elevation only adds cost, so actual cost
    >= straight-line XY distance).

    A "goal-snap" edge is added whenever the goal lies within `hop_radius`
    of the current cell, so the planner can land exactly on the goal
    without needing a ring sample to happen to align with it.
    """

    def __init__(
        self,
        map_env: Map2D5,
        start: tuple[float, float],
        goal: tuple[float, float],
        hop_radius: float,
        n_angles: int = 16,
        max_jump_height: float = 0.5,
        alpha_uphill: float = 1.0,
        alpha_downhill: float = 0.5,
        # Ballistic / clearance parameters (defaults match config.py).
        g: float = 9.81,
        V_max: float = 3.0,
        robot_radius: float = 0.1,
        clearance_margin: float = 0.15,
        clearance_weight: float = 2.0,
        arc_max_step: float = 0.05,
        arc_endpoint_epsilon: float = 0.05,
        obstacle_wall_extra: float = 1.0,
        # Demo/analysis flag: when True, skip the arc-vs-terrain clearance
        # rejection AND set the proximity penalty to zero. The Campana Eq. 4
        # + `v_s <= V_max` feasibility gate still runs (it guards physics,
        # not clearance). Intended for A/B baselines that isolate what the
        # clearance term contributes; do NOT use for real planning.
        disable_clearance: bool = False,
    ):
        self.map_env = map_env
        self.start_world = start
        self.goal_world = goal
        self.hop_radius = hop_radius
        self.n_angles = n_angles
        # Retained for backward compatibility, but the ballistic feasibility
        # gate below fully supersedes the old `|dz| <= max_jump_height` check.
        self.max_jump_height = max_jump_height
        self.alpha_uphill = alpha_uphill
        self.alpha_downhill = alpha_downhill

        # Ballistic parameters.
        self.g = g
        self.V_max = V_max
        self.robot_radius = robot_radius
        self.clearance_margin = clearance_margin
        self.clearance_weight = clearance_weight
        self.arc_max_step = arc_max_step
        self.arc_endpoint_epsilon = arc_endpoint_epsilon
        self.disable_clearance = disable_clearance

        # Height used in place of OBSTACLE sentinels when the arc-clearance
        # check bilinearly samples the terrain. Setting it well above the
        # tallest real cell makes OBSTACLE cells act as un-flyable walls.
        non_obs = map_env.grid[map_env.grid != Map2D5.OBSTACLE]
        map_max_z = float(non_obs.max()) if non_obs.size > 0 else 0.0
        self._obstacle_fill = map_max_z + obstacle_wall_extra

        # Convert start/goal to grid coordinates
        self.start_cell = map_env.world_to_grid(start[0], start[1])
        self.goal_cell = map_env.world_to_grid(goal[0], goal[1])

        # Precompute unit-vector directions for ring sampling
        angles = np.linspace(0.0, 2.0 * np.pi, n_angles, endpoint=False)
        self._hop_dirs = [(float(np.cos(a)), float(np.sin(a))) for a in angles]

    def plan(self) -> list[tuple[float, float]] | None:
        """Run A* and return the path as a list of (x, y) world coords, or None."""
        start = self.start_cell
        goal = self.goal_cell

        # Priority queue: (f_cost, counter, (row, col))
        open_set = []
        counter = 0
        heapq.heappush(open_set, (0.0, counter, start))

        # g_cost[cell] = best known cost from start to cell
        g_cost = {start: 0.0}
        # came_from[cell] = parent cell
        came_from: dict[tuple[int, int], tuple[int, int] | None] = {start: None}

        while open_set:
            f, _, current = heapq.heappop(open_set)

            if current == goal:
                return self._reconstruct_path(came_from, current)

            # Skip if we've already found a better path to this node
            if f > g_cost.get(current, float("inf")) + self._heuristic(current):
                continue

            for neighbor, edge_cost in self._generate_hop_neighbors(current):
                tentative_g = g_cost[current] + edge_cost

                if tentative_g < g_cost.get(neighbor, float("inf")):
                    g_cost[neighbor] = tentative_g
                    came_from[neighbor] = current
                    f_cost = tentative_g + self._heuristic(neighbor)
                    counter += 1
                    heapq.heappush(open_set, (f_cost, counter, neighbor))

        return None  # No path found

    def _generate_hop_neighbors(
        self,
        current: tuple[int, int],
    ) -> list[tuple[tuple[int, int], float]]:
        """Yield (neighbor_cell, edge_cost) pairs reachable from `current` in one hop.

        Neighbors are grid cells whose centers are ~hop_radius away in xy,
        found by sampling `n_angles` directions on the ring. A "goal-snap"
        edge is also added when the goal lies within hop_radius, so the goal
        can be landed on exactly regardless of angular alignment.
        """
        cx, cy = self.map_env.grid_to_world(current[0], current[1])
        current_z = self.map_env.grid[current[0], current[1]]

        results: list[tuple[tuple[int, int], float]] = []
        seen: set[tuple[int, int]] = {current}

        # Ring samples at radius = hop_radius
        for dx, dy in self._hop_dirs:
            tx = cx + self.hop_radius * dx
            ty = cy + self.hop_radius * dy

            # Reject candidates outside the map
            if not self.map_env.is_within_bounds(tx, ty):
                continue

            neighbor = self.map_env.world_to_grid(tx, ty)
            if neighbor in seen:
                continue
            seen.add(neighbor)

            edge = self._validate_and_cost(current, current_z, neighbor)
            if edge is not None:
                results.append((neighbor, edge))

        # Goal-snap edge: allow landing exactly on the goal when it's in range
        gx, gy = self.map_env.grid_to_world(self.goal_cell[0], self.goal_cell[1])
        if np.hypot(gx - cx, gy - cy) <= self.hop_radius and self.goal_cell not in seen:
            edge = self._validate_and_cost(current, current_z, self.goal_cell)
            if edge is not None:
                results.append((self.goal_cell, edge))

        return results

    def _validate_and_cost(
        self,
        current: tuple[int, int],
        current_z: float,
        neighbor: tuple[int, int],
    ) -> float | None:
        """Return edge cost if the hop is ballistically valid, else None.

        Sequence:
          (a) reject if the landing cell itself is an obstacle;
          (b) FEASIBILITY GATE: reject if no `alpha_s` satisfies both
              Campana Eq. 4 validity and `v_s <= V_max`;
          (c) pick `alpha_s = 0.5 * (alpha_min + alpha_max)` (Campana's
              max-margin choice; farthest from both constraint boundaries);
          (d) CLEARANCE GATE: reject if the min arc-to-terrain clearance is
              negative (arc intersects terrain);
          (e) return base edge cost + smooth proximity penalty. The penalty
              is 0 when clearance >= clearance_margin and grows linearly up
              to `clearance_weight` at zero clearance.
        """
        neighbor_z = self.map_env.grid[neighbor[0], neighbor[1]]

        # (a) Landing must not be on an obstacle.
        if neighbor_z == Map2D5.OBSTACLE:
            return None

        cx, cy = self.map_env.grid_to_world(current[0], current[1])
        nx, ny = self.map_env.grid_to_world(neighbor[0], neighbor[1])
        X = float(math.hypot(nx - cx, ny - cy))
        Z = float(neighbor_z - current_z)

        # (b) Ballistic feasibility (Campana Eq. 4 + leg-energy limit).
        interval = feasible_alpha_interval(X, Z, self.V_max, self.g)
        if interval is None:
            return None
        alpha_min, alpha_max = interval

        # (c) Max-margin takeoff angle (Campana): midpoint of the feasible
        # interval, which maximizes distance from the two constraints.
        alpha_s = 0.5 * (alpha_min + alpha_max)

        # (d) Arc-to-terrain clearance along the segment (Campana Eq. 2).
        c_s = (cx, cy, float(current_z))
        c_g = (nx, ny, float(neighbor_z))
        mc = min_clearance(
            c_s, c_g, alpha_s,
            self.map_env,
            self.g,
            self.robot_radius,
            self.arc_endpoint_epsilon,
            self.arc_max_step,
            self._obstacle_fill,
        )
        if not self.disable_clearance and mc < 0.0:
            return None  # arc intersects terrain -> untraversable

        # (e) Base cost + smooth proximity penalty. Penalty is 0 when
        # clearance is ample and grows linearly as it shrinks toward 0.
        # When `disable_clearance` is set (A/B baseline), the penalty is
        # suppressed too so the base cost is what A* minimises.
        base = self._edge_cost(current, neighbor, Z)
        if self.disable_clearance:
            penalty = 0.0
        elif mc < self.clearance_margin:
            penalty = (
                self.clearance_weight
                * (self.clearance_margin - mc)
                / self.clearance_margin
            )
        else:
            penalty = 0.0
        return base + penalty

    def _edge_cost(
        self,
        current: tuple[int, int],
        neighbor: tuple[int, int],
        dz: float,
    ) -> float:
        """Cost of hopping from `current` to `neighbor`.

        Cost = actual Euclidean xy-distance between cell centers + elevation
        penalty (asymmetric: uphill and downhill weighted differently).
        """
        cx, cy = self.map_env.grid_to_world(current[0], current[1])
        nx, ny = self.map_env.grid_to_world(neighbor[0], neighbor[1])
        xy_dist = float(np.hypot(nx - cx, ny - cy))

        if dz > 0:
            elevation_penalty = self.alpha_uphill * dz
        elif dz < 0:
            elevation_penalty = self.alpha_downhill * abs(dz)
        else:
            elevation_penalty = 0.0

        return xy_dist + elevation_penalty

    def _heuristic(self, cell: tuple[int, int]) -> float:
        """Admissible heuristic: Euclidean distance in world coordinates to goal.

        Admissible because sum of hop xy-distances >= straight-line distance
        (triangle inequality), and elevation + proximity penalties only add
        to the actual g-cost.
        """
        x1, y1 = self.map_env.grid_to_world(cell[0], cell[1])
        x2, y2 = self.map_env.grid_to_world(self.goal_cell[0], self.goal_cell[1])
        return float(np.hypot(x1 - x2, y1 - y2))

    def _reconstruct_path(
        self,
        came_from: dict[tuple[int, int], tuple[int, int] | None],
        current: tuple[int, int],
    ) -> list[tuple[float, float]]:
        """Trace back from goal to start, return path in world coordinates."""
        path_cells = []
        while current is not None:
            path_cells.append(current)
            current = came_from[current]
        path_cells.reverse()

        path = []
        for row, col in path_cells:
            x, y = self.map_env.grid_to_world(row, col)
            path.append((x, y))
        return path
